/** Compute human-readable name & keywords for any codepoint in our catalog. */
export function describeCodepoint(cp, blockName = '') {
  const known = CHAR_NAMES[cp];
  if (known) return { name: known[0], keywords: known[1] };

  if (cp >= 0x0030 && cp <= 0x0039) {
    const names = ['ZERO', 'ONE', 'TWO', 'THREE', 'FOUR', 'FIVE', 'SIX', 'SEVEN', 'EIGHT', 'NINE'];
    const w = names[cp - 0x0030];
    return { name: `DIGIT ${w}`, keywords: `number digit ${cp - 0x0030}` };
  }
  if (cp >= 0x0041 && cp <= 0x005A) {
    const ch = String.fromCodePoint(cp);
    return { name: `LATIN CAPITAL LETTER ${ch}`, keywords: `letter uppercase latin ${ch.toLowerCase()}` };
  }
  if (cp >= 0x0061 && cp <= 0x007A) {
    const ch = String.fromCodePoint(cp).toUpperCase();
    return { name: `LATIN SMALL LETTER ${ch}`, keywords: `letter lowercase latin ${ch.toLowerCase()}` };
  }
  if (cp >= 0x00C0 && cp <= 0x00FF) {
    const latin1Base = 'AAAAAAACEEEEIIIIDNOOOOOxOUUUUYTsaaaaaaaceeeeiiiidnooooo/ouuuuyty';
    const base = latin1Base[cp - 0x00C0] || 'A';
    const cased = cp < 0x00E0 ? 'CAPITAL' : 'SMALL';
    return { name: `LATIN ${cased} LETTER ${base.toUpperCase()} WITH DIACRITIC`, keywords: `latin accented ${base.toLowerCase()}` };
  }
  if (cp >= 0x0100 && cp <= 0x017F) {
    const hex = cp.toString(16).toUpperCase().padStart(4, '0');
    const cased = (cp % 2 === 0) ? 'CAPITAL' : 'SMALL';
    return { name: `LATIN EXTENDED-A ${cased} LETTER (U+${hex})`, keywords: 'latin extended letter' };
  }
  if (cp >= 0x0410 && cp <= 0x044F) {
    const cased = cp < 0x0430 ? 'CAPITAL' : 'SMALL';
    const idx = (cp < 0x0430 ? cp - 0x0410 : cp - 0x0430) + 1;
    return { name: `CYRILLIC ${cased} LETTER #${idx}`, keywords: 'cyrillic letter russian slavic' };
  }
  if (cp >= 0x2800 && cp <= 0x28FF) {
    const bits = cp - 0x2800;
    if (bits === 0) return { name: 'BRAILLE PATTERN BLANK', keywords: 'braille empty space dots' };
    let dots = '';
    for (let b = 0; b < 8; b++) if (bits & (1 << b)) dots += String(b + 1);
    return { name: `BRAILLE PATTERN DOTS-${dots}`, keywords: `braille dots ${dots}` };
  }
  const hex = cp.toString(16).toUpperCase().padStart(4, '0');
  const prefix = blockName ? blockName.toUpperCase() : 'UNICODE';
  return { name: `${prefix} U+${hex}`, keywords: blockName.toLowerCase() };
}
